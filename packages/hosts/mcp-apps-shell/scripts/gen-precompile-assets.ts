import { createHash } from "node:crypto";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

import { ARTIFACT_JSX_TRANSFORM_OPTIONS } from "../src/shell/compile-jsx";

/**
 * Generates the two committed files the server precompiler needs:
 *  - `assets.gen.ts`: the theme source and Tailwind's four CSS sources, as
 *    strings, because a Worker has no filesystem to read them from.
 *  - `compile-fingerprint.gen.ts`: one hash over everything that can change a
 *    compiled artifact. The shell imports only this file.
 *
 * `compile-fingerprint.pin.test.ts` regenerates both in memory and fails when
 * the committed files are stale. Run with `bun run gen:precompile`.
 */

const packageRoot = path.resolve(import.meta.dirname, "..");
const require = createRequire(path.join(packageRoot, "package.json"));

const readPackageVersion = (name: string): string => {
  let dir = path.dirname(require.resolve(name));
  while (!fs.existsSync(path.join(dir, "package.json"))) dir = path.dirname(dir);
  const manifest: { readonly version: string } = JSON.parse(
    fs.readFileSync(path.join(dir, "package.json"), "utf8"),
  );
  return manifest.version;
};

const tailwindDir = path.dirname(require.resolve("tailwindcss/package.json"));
const readTailwindCss = (file: string) => fs.readFileSync(path.join(tailwindDir, file), "utf8");
const read = (relative: string) => fs.readFileSync(path.join(packageRoot, relative), "utf8");

export const buildPrecompileAssets = (): {
  readonly assets: string;
  readonly fingerprint: string;
} => {
  const themeSource = read("src/shell/theme.css");
  const tailwindSources = {
    index: readTailwindCss("index.css"),
    preflight: readTailwindCss("preflight.css"),
    theme: readTailwindCss("theme.css"),
    utilities: readTailwindCss("utilities.css"),
  };

  const hash = createHash("sha256");
  hash.update(
    JSON.stringify({
      sucrase: readPackageVersion("sucrase"),
      tailwindcss: readPackageVersion("tailwindcss"),
      jsx: ARTIFACT_JSX_TRANSFORM_OPTIONS,
      themeSource,
      tailwindSources,
      compileJsx: read("src/shell/compile-jsx.ts"),
      extractCandidates: read("src/precompile/extract-candidates.ts"),
    }),
  );
  const fingerprint = hash.digest("hex");

  const assets = `/**
 * GENERATED by \`scripts/gen-precompile-assets.ts\`. Do not hand-edit:
 * \`compile-fingerprint.pin.test.ts\` fails if this drifts. Regenerate with
 * \`bun run gen:precompile\`.
 */

// oxfmt-ignore
export const THEME_SOURCE: string = ${JSON.stringify(themeSource)};

// oxfmt-ignore
export const TAILWIND_SOURCES = ${JSON.stringify(tailwindSources, null, 2)} as const;
`;

  return { assets, fingerprint };
};

if (import.meta.main) {
  const { assets, fingerprint } = buildPrecompileAssets();
  const dir = path.join(packageRoot, "src/precompile");
  fs.writeFileSync(path.join(dir, "assets.gen.ts"), assets);
  fs.writeFileSync(
    path.join(dir, "compile-fingerprint.gen.ts"),
    `/**
 * GENERATED by \`scripts/gen-precompile-assets.ts\`. Do not hand-edit:
 * \`compile-fingerprint.pin.test.ts\` fails if this drifts. Regenerate with
 * \`bun run gen:precompile\`.
 */

// oxfmt-ignore
export const ARTIFACT_COMPILE_FINGERPRINT = ${JSON.stringify(fingerprint)};
`,
  );
}
